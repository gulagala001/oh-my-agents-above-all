import test from 'node:test';
import assert from 'node:assert/strict';
import { writeFile, readFile, mkdir } from 'node:fs/promises';
import { join } from 'node:path';
import { chromium } from 'playwright';
import { installedHost, textReply, until } from './fixtures/installed-host.mjs';

test('Pi native tree navigation and extension compaction preserve branches across cold recovery', { timeout: 90000 }, async t => {
  const f = await installedHost(t, { safeEnvironment: true, sourceLinked: true });
  const extension = join(f.workspace, 'tree.ts'), trace = join(f.workspace, 'tree.jsonl');
  await writeFile(extension, `import {appendFile} from 'node:fs/promises';
export default function(pi){
 const log=e=>appendFile(${JSON.stringify(trace)},JSON.stringify(e)+'\\n');
 pi.on('session_before_tree',async(e,ctx)=>{
   await log({type:e.type,old:e.preparation.oldLeafId,departed:e.preparation.entriesToSummarize.length,tree:ctx.sessionManager.getTree().length,signal:e.signal.aborted});
   if(e.preparation.label==='CANCEL')return{cancel:true};
   if(e.preparation.label==='DEFAULT')return;
   if(e.preparation.label==='WAIT'){await log({type:'wait-ready'});await new Promise(r=>setTimeout(r,30000));return;}
   if(e.preparation.userWantsSummary)return{summary:{summary:'TREE_EXTENSION_SUMMARY',details:{kept:true}},label:'Saved branch'};
 });
 pi.on('session_tree',log);
 pi.on('session_before_compact',async(e,ctx)=>{
   if(!(e.preparation.fileOps.read instanceof Set))throw Error('fileOps must contain Sets');
   await log({type:e.type,reason:e.reason,branch:ctx.sessionManager.getBranch().map(e=>e.id)});
   if(e.customInstructions==='CANCEL')return{cancel:true};
   if(e.customInstructions==='INVALID')return{compaction:{summary:'INVALID_SUMMARY',firstKeptEntryId:'missing',tokensBefore:10}};
   if(e.customInstructions==='DEFAULT')return;
   return{compaction:{summary:'COMPACT_EXTENSION_SUMMARY',firstKeptEntryId:e.preparation.firstKeptEntryId,tokensBefore:e.preparation.tokensBefore,details:{ok:true}}};
 });
 pi.on('session_compact',log);pi.on('session_compact_failed',log);
 pi.registerCommand('tree_jump',{description:'Jump via extension context',async handler(args,ctx){const r=await ctx.navigateTree(args);await log({type:'command-navigate',r,leaf:ctx.sessionManager.getLeafId()});}});
 pi.registerCommand('tree_compact',{description:'Compact via extension context',async handler(args,ctx){await ctx.compact({customInstructions:args,onComplete:r=>log({type:'compact-callback',summary:r?.summary})});}});
}`);
  await f.install(); await f.boot();
  const headers = { cookie: f.cookie, 'content-type': 'application/json' };
  const settings = await fetch(f.origin + '/omaa/api/pi-extensions', { headers }).then(r => r.json());
  assert.equal((await fetch(f.origin + '/omaa/api/pi-extensions', { method: 'POST', headers, body: JSON.stringify({ revision: settings.revision, files: [extension] }) })).status, 200);
  const api = async (id, body) => { const r = await fetch(f.origin + '/omaa/api/pi-branches?session=' + id, { headers: { ...headers, cookie: f.cookie }, ...(body ? { method: 'POST', body: JSON.stringify(body) } : {}) }); const value = await r.json(); assert.equal(r.status, 200, JSON.stringify(value)); return value; };
  const rows = async () => (await readFile(trace, 'utf8')).trim().split('\n').filter(Boolean).map(JSON.parse);
  const workspace = await f.rpc('workspace/create', { path: f.workspace });
  const { sessionId } = await f.rpc('session/create', { workspaceId: workspace.workspace.workspaceId, agentPreset: 'omaa-pi' });
  f.replyWith(request => textReply(request.tools?.length ? 'REPLY_' + JSON.stringify(request.messages).match(/INPUT_[A-Z]+/g)?.at(-1) : 'DEFAULT_PI_SUMMARY'));
  await f.prompt(sessionId, 'INPUT_A');
  await f.prompt(sessionId, 'INPUT_B');
  let state = await api(sessionId); assert(state.tree?.nodes.length, JSON.stringify(state));
  const a = state.tree.nodes.find(n => n.role === 'assistant' && n.text.includes('INPUT_A'));
  const b = state.tree.nodes.find(n => n.role === 'assistant' && n.text.includes('INPUT_B'));
  const navigate = (targetId, extra = {}) => api(sessionId, { action: 'navigate', head: state.tree.head, targetId, ...extra });
  const cancelled = await navigate(a.id, { label: 'CANCEL' }); assert(cancelled.cancelled);
  assert.equal((await api(sessionId)).tree.leafId, b.id);
  const moved = await navigate(a.id, { summarize: true }); assert(!moved.cancelled); assert(moved.summaryEntry.summary.includes('TREE_EXTENSION_SUMMARY'));
  await f.prompt(sessionId, 'INPUT_C');
  let request = f.requests.filter(r => r.tools?.length).at(-1);
  assert(JSON.stringify(request.messages).includes('INPUT_A'));
  assert(JSON.stringify(request.messages).includes('TREE_EXTENSION_SUMMARY'));
  assert(!JSON.stringify(request.messages).includes('INPUT_B'));
  state = await api(sessionId);
  const c = state.tree.nodes.find(n => n.role === 'assistant' && n.text.includes('INPUT_C'));
  assert(state.tree.nodes.some(n => n.id === b.id));
  await f.call('commands/execute', { agentId: sessionId, line: '/tree_jump ' + b.id, submittedAttachments: [] });
  await f.prompt(sessionId, 'INPUT_D');
  request = f.requests.filter(r => r.tools?.length).at(-1);
  assert(JSON.stringify(request.messages).includes('INPUT_B'));
  assert(!JSON.stringify(request.messages).includes('INPUT_C'));
  assert(!JSON.stringify(request.messages).includes('TREE_EXTENSION_SUMMARY'));
  await f.call('commands/execute', { agentId: sessionId, line: '/tree_compact CUSTOM', submittedAttachments: [] });
  assert((await rows()).some(e => e.type === 'session_compact' && e.fromExtension));
  await f.stop(); await f.boot();
  await f.prompt(sessionId, 'INPUT_E');
  request = f.requests.filter(r => r.tools?.length).at(-1);
  assert(JSON.stringify(request.messages).includes('COMPACT_EXTENSION_SUMMARY'));
  assert(!JSON.stringify(request.messages).includes('INPUT_A'));
  assert(!JSON.stringify(request.messages).includes('INPUT_C'));
  state = await api(sessionId);
  await navigate(c.id);
  await f.prompt(sessionId, 'INPUT_F');
  request = f.requests.filter(r => r.tools?.length).at(-1);
  assert(JSON.stringify(request.messages).includes('INPUT_C'));
  assert(!JSON.stringify(request.messages).includes('COMPACT_EXTENSION_SUMMARY'));
  await f.call('commands/execute', { agentId: sessionId, line: '/compact DEFAULT', submittedAttachments: [] });
  await f.prompt(sessionId, 'INPUT_G');
  assert(JSON.stringify(f.requests.filter(r => r.tools?.length).at(-1).messages).includes('DEFAULT_PI_SUMMARY'));
  state = await api(sessionId);
  await navigate(b.id, { summarize: true, label: 'DEFAULT' });
  await f.prompt(sessionId, 'INPUT_H');
  assert(JSON.stringify(f.requests.filter(r => r.tools?.length).at(-1).messages).includes('DEFAULT_PI_SUMMARY'));
  state = await api(sessionId);
  const failedCompact = async customInstructions => {
    const before = (await api(sessionId)).tree;
    const r = await fetch(f.origin + '/omaa/api/pi-branches?session=' + sessionId, { method: 'POST', headers: { ...headers, cookie: f.cookie },
      body: JSON.stringify({ action: 'compact', head: before.head, customInstructions }) });
    assert.notEqual(r.status, 200); assert.equal((await api(sessionId)).tree.leafId, before.leafId);
  };
  await failedCompact('INVALID'); await failedCompact('CANCEL');
  const beforeCancel = state.tree.leafId;
  const pending = fetch(f.origin + '/omaa/api/pi-branches?session=' + sessionId, { method: 'POST', headers: { ...headers, cookie: f.cookie },
    body: JSON.stringify({ action: 'navigate', head: state.tree.head, targetId: a.id, label: 'WAIT' }) });
  await until(async () => (await rows()).some(row => row.type === 'wait-ready'));
  assert.equal((await f.api(sessionId)).value.running, true);
  await f.rpc('session/cancel', { sessionId }); assert.notEqual((await pending).status, 200);
  assert.equal((await api(sessionId)).tree.leafId, beforeCancel);
  // Reload the canceled guest on the next actual turn, then trigger Pi's
  // pressure policy using a real per-project setting and a long local input.
  await mkdir(join(f.workspace, '.pi'), { recursive: true });
  await writeFile(join(f.workspace, '.pi/settings.json'), JSON.stringify({ compaction: { enabled: false, reserveTokens: 995000, keepRecentTokens: 0 } }));
  await f.prompt(sessionId, 'INPUT_LONG ' + 'local context '.repeat(5000));
  assert(!(await rows()).some(row => row.type === 'session_before_compact' && row.reason === 'threshold'));
  await writeFile(join(f.workspace, '.pi/settings.json'), JSON.stringify({ compaction: { enabled: true, reserveTokens: 995000, keepRecentTokens: 0 } }));
  await f.prompt(sessionId, 'INPUT_PRESSURE');
  assert((await rows()).some(row => row.type === 'session_compact' && row.reason === 'threshold'));
  assert(!JSON.stringify(f.requests.filter(r => r.tools?.length).at(-1).messages).includes('local context local context'));
  await writeFile(join(f.workspace, '.pi/settings.json'), JSON.stringify({ compaction: { enabled: false } }));
  await f.rpc('session/rename', { sessionId, title: 'Pi tree native flow' });
  const browser = await chromium.launch({ headless: true, args: ['--use-mock-keychain', '--password-store=basic'] });
  t.after(() => browser.close());
  const browserContext = await browser.newContext({ timezoneId: 'UTC', viewport: { width: 1440, height: 1100 } });
  await browserContext.addCookies(f.cookie.split('; ').map(value => { const at = value.indexOf('='); return { name: value.slice(0, at), value: value.slice(at + 1), url: f.origin }; }));
  const page = await browserContext.newPage(); page.setDefaultTimeout(12000);
  await page.goto(f.origin); await page.getByRole('button', { name: /^(Continue|继续)$/ }).click();
  await page.getByText('Pi tree native flow', { exact: true }).first().click();
  await page.getByRole('button', { name: 'Pi Coding Agent 预设设置', exact: true }).click();
  const panel = page.getByRole('region', { name: 'Pi 分支导航' });
  await panel.getByLabel('Pi 历史节点').selectOption(a.id);
  await panel.getByRole('button', { name: '切换到历史节点', exact: true }).click();
  await panel.getByText('已切换历史节点；下一条输入从此处分支。', { exact: true }).waitFor();
  state = await api(sessionId); assert.equal(state.tree.leafId, a.id);
  const userB = state.tree.nodes.find(node => node.role === 'user' && node.text === 'INPUT_B');
  await panel.getByLabel('Pi 历史节点').selectOption(userB.id);
  await panel.getByRole('button', { name: '切换到历史节点', exact: true }).click();
  await panel.getByLabel('编辑 Pi 历史输入').fill('INPUT_UI_EDITED');
  await panel.getByRole('button', { name: '从此处发送', exact: true }).click();
  await until(async () => f.requests.some(request => request.tools?.length && JSON.stringify(request.messages).includes('INPUT_UI_EDITED'))).catch(async error => { t.diagnostic((await panel.innerText()).slice(-2400)); t.diagnostic(JSON.stringify((await f.snapshot(sessionId)).records.slice(-5))); throw error; });
  await until(async () => !(await f.api(sessionId)).value.running);
  request = f.requests.filter(r => r.tools?.length).at(-1); assert(!JSON.stringify(request.messages).includes('INPUT_B'));
  const compactReply = page.waitForResponse(response => response.url().includes('/omaa/api/pi-branches') && response.request().method() === 'POST');
  await panel.getByRole('button', { name: '压缩当前分支', exact: true }).click();
  const compactResponse = await compactReply.catch(async error => { t.diagnostic((await panel.innerText()).slice(-1800)); await page.screenshot({ path: new URL('../ui-failure.png', import.meta.url).pathname.replace('/worktree/ui-failure.png', '/ui-failure.png') }); throw error; }); const compactText = await compactResponse.text(); assert.equal(compactResponse.status(), 200, compactText); t.diagnostic('compact reply: ' + compactText);
  await panel.getByText('当前分支已压缩。', { exact: true }).waitFor().catch(async error => { t.diagnostic((await panel.innerText()).slice(-2000)); throw error; });
  await panel.scrollIntoViewIfNeeded(); await page.screenshot({ path: new URL('../ui.png', import.meta.url).pathname.replace('/worktree/ui.png', '/ui.png') });
  await browser.close();
  await writeFile(join(f.workspace, '.pi/settings.json'), JSON.stringify({ compaction: { enabled: true } }));
  let overflowCalls = 0;
  f.replyWith(request => {
    if (!request.tools?.length) return textReply('Auxiliary local reply');
    if (overflowCalls++ === 0) return { httpStatus: 400, body: { error: { message: 'maximum context length exceeded', type: 'invalid_request_error', code: 'context_length_exceeded' } } };
    return textReply('OVERFLOW_RETRIED');
  });
  await f.prompt(sessionId, 'INPUT_OVERFLOW');
  assert.equal(overflowCalls, 2);
  assert((await rows()).some(row => row.type === 'session_compact' && row.reason === 'overflow' && row.willRetry === true));
  const raw = (await f.snapshot(sessionId)).records;
  assert(JSON.stringify(raw).includes('INPUT_B') && JSON.stringify(raw).includes('INPUT_C'));
  assert((await rows()).some(e => e.type === 'command-navigate'));
  if (process.env.OMAA_PI_TREE_EVIDENCE) await writeFile(process.env.OMAA_PI_TREE_EVIDENCE, JSON.stringify({ requests: f.requests.length, externalModels: 0, host: f.evidence.version,
    checks: ['same-session tree', 'cancelled navigation', 'extension summary', 'sibling branch request isolation', 'extension command navigation', 'custom compaction', 'cold branch recovery', 'restore pre-compaction branch', 'default native summary', 'raw journal preserved', 'default branch summary', 'invalid compaction rejected', 'cancellation without mutation', 'project auto-compaction settings', 'actual threshold compaction', 'native browser tree navigation', 'edited history resubmission', 'browser compact action', 'provider overflow actual retry'], events: await rows() }, null, 2));
});
