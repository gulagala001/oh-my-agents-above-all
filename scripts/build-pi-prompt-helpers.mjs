import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from 'esbuild';
import ts from 'typescript';

const root = fileURLToPath(new URL('../', import.meta.url));
const presetRoot = join(root, 'src/presets/pi');
const commit = 'cd32f7725fdbddbaecdff5b1e68491563394e0ca';
const functions = [
  ['packages/coding-agent/src/core/system-prompt.ts', ['normalizeBuildSystemPromptOptions']],
  ['packages/coding-agent/src/core/skills.ts', ['formatSkillsForPrompt', 'escapeXml']],
];
const exports = ['normalizeBuildSystemPromptOptions', 'formatSkillsForPrompt'];

async function fixedSource(manifest, path) {
  const entry = manifest.files.find(file => file.path === path);
  if (!entry || entry.snapshot !== 'sources/' + path || entry.license !== 'MIT') {
    throw new Error('Fixed Pi source metadata missing or changed: ' + path);
  }
  const bytes = await readFile(join(presetRoot, entry.snapshot));
  if (createHash('sha256').update(bytes).digest('hex') !== entry.sha256) {
    throw new Error('Fixed Pi source SHA-256 mismatch: ' + path);
  }
  return bytes.toString('utf8');
}

// Extract only the named pure declarations. The original modules' imports,
// prompt builders, resource loaders and agent/config dependencies stay out.
function extractFunctions(source, path, names) {
  const parsed = ts.createSourceFile(path, source, ts.ScriptTarget.Latest, true);
  return names.map(name => {
    const matches = parsed.statements.filter(statement =>
      ts.isFunctionDeclaration(statement) && statement.name?.text === name);
    if (matches.length !== 1 || !matches[0].body) {
      throw new Error('Fixed Pi function missing or ambiguous: ' + name);
    }
    return matches[0].getText(parsed);
  }).join('\n\n');
}

export async function buildPiPromptHelpers({ write = false, outputDir = join(root, 'lib') } = {}) {
  const manifest = JSON.parse(await readFile(join(presetRoot, 'source.json'), 'utf8'));
  if (manifest.commit !== commit || manifest.license !== 'MIT') {
    throw new Error('Fixed Pi source revision or license changed');
  }
  const license = await fixedSource(manifest, 'LICENSE');
  const declarations = [];
  for (const [path, names] of functions) {
    declarations.push(extractFunctions(await fixedSource(manifest, path), path, names));
  }
  const generated = await transform(declarations.join('\n\n'), {
    loader: 'ts', format: 'esm', target: 'es2022',
  });
  const banner = '// Generated by scripts/build-pi-prompt-helpers.mjs; do not edit.\n'
    + '// Derived from earendil-works/pi at ' + commit + '.\n'
    + '// Only normalizeBuildSystemPromptOptions, formatSkillsForPrompt and private escapeXml.\n'
    + '// See src/presets/pi/source.json and THIRD_PARTY_NOTICES.md.\n'
    + '/*\n' + license.trimEnd() + '\n*/\n';
  const content = banner + generated.code;
  const output = join(resolve(outputDir), 'pi-prompt-helpers.mjs');
  if (write) {
    await mkdir(resolve(outputDir), { recursive: true });
    await writeFile(output, content);
  } else {
    const current = await readFile(output, 'utf8').catch(error => {
      if (error.code === 'ENOENT') return null;
      throw error;
    });
    if (current !== content) throw new Error('Pi prompt helpers are missing or stale; run with --write: ' + output);
  }
  return { output, exports, inputs: functions.length + 1, mode: write ? 'write' : 'check' };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  let write = false, mode, outputDir;
  for (let index = 2; index < process.argv.length; index++) {
    const argument = process.argv[index];
    if (argument === '--write' || argument === '--check') {
      if (mode && mode !== argument) throw new Error('Use either --check or --write');
      mode = argument;
      write = argument === '--write';
    } else if (argument === '--output-dir') {
      outputDir = process.argv[++index];
      if (!outputDir || outputDir.startsWith('--')) throw new Error('--output-dir requires a directory');
    } else {
      throw new Error('Unknown Pi prompt helpers build argument: ' + argument);
    }
  }
  const result = await buildPiPromptHelpers({ write, outputDir });
  process.stdout.write('Pi prompt helpers ' + result.mode + ': ' + result.output + '\n');
}
